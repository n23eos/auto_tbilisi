// Переход к заявке зависит от итога попытки, но не меняет правила экзамена.
export function learningNextStep(verdict) {
  if (verdict.passed) {
    return {
      goal: 'practice',
      title: 'Теперь попробуйте за рулём',
      text: 'С этой попыткой вы справились. Если готовы перейти к вождению, подберём занятие на площадке или в городе под ваш опыт.',
      label: 'Подобрать вождение',
    };
  }
  return {
    goal: 'theory',
    title: verdict.reason === 'time' ? 'Разберитесь в своём темпе' : 'Разберём то, что не получилось',
    text: verdict.reason === 'time'
      ? 'Попробуйте тренировку без таймера. А если нужна помощь с правилами — обсудите с преподавателем подходящий формат теории.'
      : 'Посмотрите ошибки ниже или вернитесь к тренировке. Если хочется разобраться с преподавателем, поможем выбрать занятия по теории.',
    label: 'Обсудить занятия по теории',
  };
}
